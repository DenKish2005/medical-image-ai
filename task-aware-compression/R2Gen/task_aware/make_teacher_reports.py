"""Generate the uncompressed R2Gen report for every cached study (the "teacher" reports).

These reports are the target for train_codec_fidelity.py: the codec is trained to make R2Gen
produce the SAME report from the compressed feature as from the uncompressed feature.
No reference report is used. Decoding settings must be the ones used in evaluate.py.

    python task_aware/make_teacher_reports.py --feature_dir ../results/ta_features \
        --out ../results/ta_full/teacher_reports.json \
        --check ../results/ta_full/eval_compare_r500/per_study.json -- <R2Gen args>
"""
import argparse
import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ta_common as tc  # noqa: E402


def main():
    mine, theirs = tc.split_argv()
    p = argparse.ArgumentParser()
    p.add_argument('--feature_dir', required=True)
    p.add_argument('--out', required=True)
    p.add_argument('--splits', nargs='+', default=['train', 'val'])
    p.add_argument('--batch_size', type=int, default=16)
    p.add_argument('--max_n', type=int, default=0, help='only the first N studies per split (smoke tests)')
    p.add_argument('--check', default=None,
                   help='an existing evaluate.py per_study.json; its condition A must match the val reports')
    p.add_argument('--device', default='cuda' if torch.cuda.is_available() else 'cpu')
    a = p.parse_args(mine)
    args = tc.r2gen_args(theirs)
    tc.fix_seed(args.seed)
    device = torch.device(a.device)
    r2, tokenizer = tc.load_frozen_r2gen(args, device)

    reports = {}
    for split in a.splits:
        store = tc.FeatureStore(a.feature_dir, split)
        out = {}
        n_use = min(a.max_n, len(store)) if a.max_n else len(store)
        for i in range(0, n_use, a.batch_size):
            idx = list(range(i, min(n_use, i + a.batch_size)))
            x = store.batch(idx, device)
            gen = r2.generate(*tc.views(x))
            for j, text in zip(idx, gen):
                if not text.strip():
                    raise RuntimeError(f'empty generated report for {store.ids[j]}')
                words = text.split()
                # Same token ids after cleaning. A report cut at max_seq_length has no final '.', and the
                # cleaner appends one; the trainer truncates to max_seq_length, so a longer tail is harmless.
                # '<unk>' is cleaned to 'unk', which maps back to the <unk> id, so compare token ids.
                ids = [tokenizer.get_id_by_token(w) for w in words]
                cleaned = [tokenizer.get_id_by_token(w) for w in tokenizer.clean_report(text).split()]
                if cleaned[:len(ids)] != ids:
                    raise RuntimeError(f'generated report is not stable under clean_report: {store.ids[j]}')
                out[store.ids[j]] = text
            print(f'\r{split}: {len(out)}/{n_use}', end='', flush=True)
        print(f'  ({len(set(out.values()))} distinct reports)')
        reports[split] = out

    if a.check:
        ref = {r['id']: r['generated'] for r in json.loads(Path(a.check).read_text())['A']}
        got = reports.get('val', {})
        common = [k for k in ref if k in got]
        bad = [k for k in common if ref[k] != got[k]]
        print(f'check against {a.check}: {len(common) - len(bad)}/{len(common)} val reports identical')
        if not common or bad:
            raise RuntimeError('Teacher reports differ from the saved uncompressed reports; '
                               'use the same decoding arguments as evaluate.py.')

    tc.json_save(a.out, {
        'what': 'reports generated by the frozen R2Gen from UNCOMPRESSED cached features',
        'r2gen_checkpoint_sha256': tc.sha256_file(args.load),
        'decoding': {k: getattr(args, k) for k in ('sample_method', 'beam_size', 'block_trigrams', 'max_seq_length')},
        'reports': reports})
    print('saved', Path(a.out).resolve())


if __name__ == '__main__':
    main()
